import hashlib
import json
from pathlib import Path
from chicken_chaser.contracts import ROOT, load_config


def generate(path=ROOT / "config/runtime.yaml", destination=ROOT / "firmware/generated_config.hpp"):
    """Purpose: Prevent host/MCU config drift. Design: include authority digest;
    validate first. Workflow: before build. Data Handoff: generated header with
    simulation-only constants; hardware output remains disabled.
    """
    config = load_config(path)
    sim = config["simulation"]
    behavior = config["behavior"]
    if behavior["max_turn"] > sim["max_duty"] or behavior["max_forward"] + behavior["max_turn"] > sim["max_duty"]:
        raise ValueError("Behavior mix exceeds motor limit")
    if sim["deadband"] >= sim["max_duty"]:
        raise ValueError("Motor deadband must be below limit")
    digest = hashlib.sha256(json.dumps(config, sort_keys=True).encode()).hexdigest()
    fields = [str(sim["lease_ms"]), str(sim["sensor_age_ms"]), str(sim["clearance_mm"]),
              str(sim["reversal_ms"]), str(behavior["observation_age_ms"]),
              f'{sim["max_duty"]:.9f}f', f'{sim["deadband"]:.9f}f', f'{sim["ramp_per_s"]:.9f}f',
              str(behavior["follow_enabled"]).lower()]
    content = '// Generated by tools/generate_mcu.py; simulation only. Do not edit.\n#pragma once\n#include "core.hpp"\n'
    content += f'inline constexpr char CONFIG_SHA256[] = "{digest}";\n'
    content += 'inline constexpr bool PHYSICAL_OUTPUTS = false;\n'
    content += 'inline constexpr chicken::Config SIM_CONFIG{' + ', '.join(fields) + '};\n'
    Path(destination).write_text(content)
    return digest


if __name__ == "__main__":
    print(generate())
